##Is : Returns true if both variables are the same object(x is y) else false
print('1 is 1:', 1 is 1) # True
print('1 is 2:', 1 is 2) # False
##Is not : Returns true if both variables are not the same object(x is not y) else false
print('1 is not 2:', 1 is not 2) # True
##in : Returns true if a sequence with the specified value is present in the object
print('a in Asabeneh:', 'a' in 'Asabeneh') # True
##not in : Returns true if a sequence with the specified value is not present in the object
print('B not in Asabeneh:', 'B' not in 'Asabeneh') # True

###Logical Operators
# and : Returns True if both statements are true
# or : Returns True if one of the statements is true
# not : Reverse the result, returns False if the result is true

